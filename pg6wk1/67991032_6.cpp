/*
1. Reference
-Used to create another name for an existing variable. It allows us to access or modify the original variable without copying its value. 
It is useful when passing variables to functions because it can avoid unnecessary copying.
2. Namespace
-Used to organize code and prevent naming conflicts. It allows different functions or variables to have the same name as long as they 
belong to different namespaces. It is especially useful in large programs.
3. Class
-Used to group related data and functions together. It acts as a blueprint for creating objects. For example, in a game, a Player class 
can contain information such as HP, score, and level, as well as functions to control the player.
4. Function Overload
-Allows us to create multiple functions with the same name but different parameters. It is useful when we want to perform 
similar operations with different data types or numbers of arguments.
5. Constexpr
-Used to define values or functions that can be evaluated at compile time. It is useful for fixed values, such as maximum player numbers, 
array sizes, and mathematical calculations. This can help improve program efficiency.
*/